// Difference 13 (owner decision of 2026-11-17): on every blog page an article image /assets/<name>.png,
// absent from the old build, stands for the Astro asset /_astro/<name>.<hash>.webp built from the WebP copy
// of the same file; the article without a file (nurse-benefits) shows /og-blog.jpg. The alt is unchanged.
const blogImage = (oldSrc: string): string => {
  const name = oldSrc.match(/^\/assets\/(drips_cl2|main|WoundDressingBandage|injection)\.png$/)?.[1];
  return name ? `/_astro/${name}.webp` : '/og-blog.jpg';
};
export const blogImageReplacements: ReadonlyArray<{
  path: string;
  old: { src: string; alt: string | null };
  new: { src: string; alt: string | null };
}> = pages
  .filter((page) => page.id === 'blog' || page.id.startsWith('blog:'))
  .flatMap((page) => Object.values(page.paths))
  .flatMap((path) =>
    blogPosts.map((post) => ({
      path,
      old: { src: post.image, alt: post.title },
      new: { src: blogImage(post.image), alt: post.title },
    })),
  );

// Differences 4 and 8: a redirect source of the manifest stands for its target page; an address
// without the trailing slash stands for the page at the same address with it (the old IVF page's
// breadcrumb leads to https://www.nius.cz/en, owner decision of 2026-11-17).
export function finalPath(sitePath: string): string {
  const redirect = redirects.find((r) => r.from === sitePath);
  if (redirect) return pageUrl(redirect.to.id, redirect.to.lang);
  if (!sitePath.endsWith('/') && pages.some((page) => Object.values(page.paths).includes(`${sitePath}/`))) {
    return `${sitePath}/`;
  }
  return sitePath;
}

// Difference 5: Vite names a bundled asset /assets/<name>-<hash>.<ext>, Astro /_astro/<name>.<hash>.<ext>.
// Difference 13: a blog image replacement names the Astro asset without its hash, /_astro/<name>.<ext>.
export function sameAsset(oldSrc: string, newSrc: string): boolean {
  if (oldSrc === newSrc) return true;
  const astro = newSrc.match(/^\/_astro\/(.+)\.[\w-]{8}\.(\w+)$/);
  if (astro === null) return false;
  const vite = oldSrc.match(/^\/assets\/(.+)-[\w-]{8}\.(\w+)$/) ?? oldSrc.match(/^\/_astro\/([^./]+)\.(\w+)$/);
  return vite !== null && vite[1] === astro[1] && vite[2] === astro[2];
}
